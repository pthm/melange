// clientPlan is a client generation resolved from the flags and the
// configuration: what generate client writes, and what --check and doctor
// compare.
type clientPlan struct {
	runtime, schema, output string
	types                   []schema.TypeDefinition
	genCfg                  *clientgen.Config
	// local is the exposure the client follows, melange.yaml's sql section.
	local compiler.Exposure
}

// resolveClientPlan resolves a client generation: flags > config >
// defaults, the relation flags over generate.client.relations, which
// otherwise inherits sql.relations. Without withFlags (doctor) only the
// configuration is read.
func resolveClientPlan(cmd *cobra.Command, withFlags bool) (*clientPlan, error) {
	var runtimeFlag, schemaFlag, outputFlag, pkgFlag, filterFlag, idTypeFlag string
	client := cfg.Generate.Client
	if withFlags {
		runtimeFlag, schemaFlag, outputFlag = genClientRuntime, genClientSchema, genClientOutput
		pkgFlag, filterFlag, idTypeFlag = genClientPackage, genClientFilter, genClientIDType
		if err := applyRelationFlags(cmd.Flags(), &client.Relations); err != nil {
			return nil, err
		}
	}
	p := &clientPlan{
		runtime: resolveString(runtimeFlag, client.Runtime),
		schema:  resolveString(schemaFlag, cfg.Schema),
		output:  resolveString(outputFlag, client.Output),
		local:   cfg.SQL.Exposure(),
	}
	selector := client.RelationPatterns(cfg.SQL.Relations)

	if p.runtime == "" {
		return nil, cli.ConfigError("--runtime is required", nil)
	}
	if p.schema == "" {
		return nil, cli.ConfigError("--schema is required", nil)
	}
	if !clientgen.Registered(p.runtime) {
		return nil, cli.ConfigError(
			fmt.Sprintf("unknown runtime %q", p.runtime),
			fmt.Errorf("supported runtimes: %s", strings.Join(clientgen.ListRuntimes(), ", ")),
		)
	}
	if _, err := os.Stat(p.schema); err != nil {
		return nil, cli.SchemaParseError(fmt.Sprintf("schema not found: %s", p.schema), nil)
	}
	types, err := parser.ParseSchema(p.schema)
	if err != nil {
		return nil, cli.SchemaParseError("parsing schema", err)
	}
	p.types = types
	p.genCfg = &clientgen.Config{
		Package:        resolveString(pkgFlag, client.Package, "authz"),
		Exposure:       &p.local,
		Relations:      &selector,
		RelationFilter: resolveString(filterFlag, client.Filter),
		IDType:         resolveString(idTypeFlag, client.IDType, "string"),
		Version:        version.Version,
		SourcePath:     p.schema,
	}
	return p, nil
}

// names returns the names the client emits: the selected relations and the
// accessible function names.
func (p *clientPlan) names() (sqlapi.ClientNames, error) {
	m, err := clientmodel.Resolve(p.types, p.genCfg)
	if err != nil {
		return sqlapi.ClientNames{}, err
	}
	content, err := parser.ReadSchemaContent(p.schema)
	if err != nil {
		return sqlapi.ClientNames{}, cli.SchemaParseError("reading schema", err)
	}
	return sqlapi.NewClientNames(m, p.types, string(content)), nil
}

// checkFiles compares the files under the output directory with a fresh
// generation. The header's version and source lines are left out, so a
// file generated by another melange release or from another directory
// compares equal when nothing else changed.
func (p *clientPlan) checkFiles() ([]clientmodel.FileDrift, error) {
	genCfg := *p.genCfg
	genCfg.Version, genCfg.SourcePath = "", ""
	files, err := clientgen.Generate(p.runtime, p.types, &genCfg)
	if err != nil {
		return nil, err
	}
	return clientmodel.CompareFiles(files, p.output)
}

// runClientCheck is generate client --check: the files under the output
// directory against the configuration and, with a database, the names the
// configuration generates against the database.
func runClientCheck(p *clientPlan, dbURL, dbSchema, format string, strict bool) error {
	if p.output == "" {
		return cli.ConfigError("--check needs an output directory: set --output or generate.client.output", nil)
	}
	drift, err := p.checkFiles()
	if err != nil {
		return cli.GeneralError("generation failed", err)
	}
	var cr *sqlapi.ClientReport
	if dbURL != "" || resolveString(envFlag, os.Getenv("MELANGE_ENV")) != "" {
		if cr, err = compareClientWithDB(p, dbURL, dbSchema); err != nil {
			return err
		}
	}

	if drift == nil {
		drift = []clientmodel.FileDrift{}
	}
	w := bufio.NewWriter(os.Stdout)
	if format == "json" {
		out, err := json.MarshalIndent(struct {
			Files    []clientmodel.FileDrift `json:"files"`
			Database *sqlapi.ClientReport    `json:"database"`
		}{drift, cr}, "", "  ")
		if err != nil {
			return cli.GeneralError("encoding JSON", err)
		}
		_, _ = fmt.Fprintln(w, string(out))
	} else {
		printClientReport(w, p, drift, cr, dbSchema)
	}
	if err := w.Flush(); err != nil {
		return cli.GeneralError("writing output", err)
	}

	if len(drift) > 0 || (cr != nil && (cr.Errors > 0 || (strict && cr.Warnings > 0))) {
		return cli.GeneralError("client check failed", nil)
	}
	return nil
}

// compareClientWithDB compares the plan's names with the database, through
// doctor for the fix hints, which follow what a plain migrate would do.
func compareClientWithDB(p *clientPlan, dbURL, dbSchema string) (*sqlapi.ClientReport, error) {
	names, err := p.names()
	if err != nil {
		return nil, cli.GeneralError("generation failed", err)
	}
	dsn, err := resolveDSN(dbURL)
	if err != nil {
		return nil, err
	}
	db, err := sql.Open("postgres", dsn)
	if err != nil {
		return nil, cli.DBConnectError("connecting to database", err)
	}
	defer func() { _ = db.Close() }()
	ctx := context.Background()
	if err := db.PingContext(ctx); err != nil {
		return nil, cli.DBConnectError("connecting to database", err)
	}
	d := doctor.New(db, p.schema, doctor.Options{Exposure: &p.local})
	d.SetDatabaseSchema(dbSchema)
	cr, err := d.CompareClient(ctx, names, p.local)
	if err != nil {
		return nil, cli.GeneralError("reading the deployed SQL API", err)
	}
	return cr, nil
}

// printClientReport prints a client check as text.
func printClientReport(dst io.Writer, p *clientPlan, drift []clientmodel.FileDrift, cr *sqlapi.ClientReport, dbSchema string) {
	w := style.Writer(dst)
	st := style.StatusStyles
	severity := map[sqlapi.ClientSeverity]func(...string) string{
		sqlapi.SeverityError:   st.Bad.Render,
		sqlapi.SeverityWarning: st.Warn.Render,
		sqlapi.SeverityInfo:    st.Muted.Render,
	}
	for _, f := range drift {
		line := filepath.Join(p.output, f.File) + ": " + f.Summary()
		// Only a file that differs has a version; a missing one has none.
		if f.OnDiskVersion != "" && f.OnDiskVersion != version.Version {
			line += fmt.Sprintf(" (generated by melange %s, this is %s)", f.OnDiskVersion, version.Version)
		}
		_, _ = fmt.Fprintln(w, st.Bad.Render(line))
	}
	if len(drift) == 0 && !quiet {
		_, _ = fmt.Fprintf(w, "%s %s matches melange.yaml\n", st.Good.Render("✓"), p.output)
	}
	if cr == nil {
		return
	}
	if len(drift) > 0 {
		_, _ = fmt.Fprintln(w, "The database check covers the names melange.yaml generates, not the ones in the files that differ.")
	}
	for _, f := range cr.Findings {
		_, _ = fmt.Fprintf(w, "%s %s: %s\n", severity[f.Severity](string(f.Severity)), f.Code, f.Message)
		if f.Fix != "" && f.Severity != sqlapi.SeverityInfo {
			_, _ = fmt.Fprintf(w, "    Fix: %s\n", f.Fix)
		}
	}
	for _, n := range cr.Notes {
		_, _ = fmt.Fprintf(w, "%s %s\n", st.Muted.Render("Note:"), n)
	}
	switch {
	case cr.Errors+cr.Warnings > 0:
		_, _ = fmt.Fprintf(w, "Database (schema %s): %d errors, %d warnings, over %d accessible function names and %d relations\n",
			dbSchema, cr.Errors, cr.Warnings, cr.FunctionsChecked, cr.PairsChecked)
	case !quiet:
		_, _ = fmt.Fprintf(w, "%s the database (schema %s) has everything the client uses (%d accessible function names, %d relations checked)\n",
			st.Good.Render("✓"), dbSchema, cr.FunctionsChecked, cr.PairsChecked)
	}
}
