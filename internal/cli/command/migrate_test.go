package command

import (
	"errors"
	"fmt"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/pthm/melange/internal/cli"
	"github.com/pthm/melange/pkg/migrator"
)

func TestMigrateExitError(t *testing.T) {
	ahead := &migrator.DatabaseAheadError{Deployed: "0.11.0", Current: "0.10.0"}
	drift := &migrator.DeployedModelChangedError{Expected: "a", Actual: "b"}
	dependents := &migrator.DependentObjectsError{Dependents: []migrator.FunctionDependent{
		{Object: "policy docs_read on table docs", Function: "accessible_document_viewer"},
	}}
	tests := []struct {
		name string
		err  error
		code int
		as   any
	}{
		// Startup scripts treat exit 5 as "another replica already upgraded".
		{"database ahead", fmt.Errorf("migrating: %w", ahead), cli.ExitDatabaseAhead, new(*migrator.DatabaseAheadError)},
		{"drift", fmt.Errorf("migrating: %w", drift), cli.ExitGeneral, new(*migrator.DeployedModelChangedError)},
		{"dependents", fmt.Errorf("migrating: %w", dependents), cli.ExitGeneral, new(*migrator.DependentObjectsError)},
		{"schema parse", errors.New("parsing schema: unexpected token"), cli.ExitSchemaParse, nil},
		{"other", errors.New("connection reset"), cli.ExitGeneral, nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := migrateExitError(tt.err)
			var exitErr *cli.ExitError
			require.ErrorAs(t, err, &exitErr)
			require.Equal(t, tt.code, exitErr.Code)
			if tt.as != nil {
				require.ErrorAs(t, err, tt.as, "the typed migrator error must stay in the chain")
			}
		})
	}
	require.Contains(t, migrateExitError(ahead).Error(), "generated by melange 0.11.0, newer than this melange (0.10.0)")
	msg := migrateExitError(dependents).Error()
	require.Contains(t, msg, "--force")
	require.Contains(t, msg, "policy docs_read on table docs depends on accessible_document_viewer")
}
