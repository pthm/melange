// CodegenVersion returns the melange version used to identify which codegen
// produced the SQL. Combined with function checksums, this allows skip detection
// and change tracking across migrations.
func CodegenVersion() string {
	return version.Short()
}

// MigrateOptions controls migration behavior (public API).
type MigrateOptions struct {
	// DryRun outputs SQL to the provided writer without applying changes to the database.
	// If nil, migration proceeds normally. Use for previewing migrations or generating migration scripts.
	DryRun io.Writer

	// Force re-runs migration even if schema/codegen unchanged. Use when manually fixing corrupted state or testing.
	// It also overrides the downgrade guard (see DatabaseAheadError), so an older
	// melange can deliberately replace functions generated by a newer one, and
	// the dependent-object refusal (see DependentObjectsError): orphaned
	// functions are dropped with CASCADE, together with any views, policies,
	// rules or functions that depend on them.
	Force bool

	// Version is the melange CLI/library version (e.g., "v0.4.3").
	// Recorded in melange_migrations for traceability.
	Version string

	// DatabaseSchema is the Postgres schema where the objects will be created.
	DatabaseSchema string

	// IfDeployedChecksum, when non-nil, makes migration a compare-and-swap: it
	// proceeds only if the currently-deployed schema checksum equals the pointed-to
	// value, otherwise it aborts with *DeployedModelChangedError without applying
	// anything. An empty string matches a database with no migration recorded. It
	// is enforced in dry-run too, so a drift-gated preview aborts rather than
	// printing SQL against a drifted database.
	//
	// The checksum is verified up front and again inside the apply transaction,
	// which holds the migration lock, so a migration committed while this one
	// waited aborts it.
	IfDeployedChecksum *string

	// Exposure selects the generated SQL API (see [Exposure]). Nil keeps the
	// exposure the database was last migrated with (the default when none is
	// recorded), so an application that migrates on startup does not undo an
	// exposure set by `melange migrate`. A non-nil value replaces it; pass a
	// pointer to the zero value to restore the default.
	Exposure *Exposure
}

// InternalMigrateOptions extends MigrateOptions with internal fields.
type InternalMigrateOptions struct {
	DryRun io.Writer
	Force  bool

	// Version is the melange CLI/library version (e.g., "v0.4.3").
	// Recorded in melange_migrations for traceability.
	Version string

	// SchemaContent is the raw schema text used for checksum calculation to detect schema changes.
	// If empty, no migration is recorded: skip-if-unchanged optimization is
	// disabled, and an Exposure other than the recorded one is refused (see
	// UnrecordedExposureChangeError) unless DryRun is set.
	SchemaContent string

	// SchemaFormat records how the schema was authored: "single" for a .fga
	// file or "modular" for an fga.mod manifest. Stored alongside the DSL so
	// `melange schema pull` can annotate its output.
	SchemaFormat string

	// IfDeployedChecksum is the compare-and-swap precondition; see MigrateOptions.
	IfDeployedChecksum *string

	// Exposure selects the generated SQL API; see MigrateOptions. Nil falls
	// back to the Migrator's exposure (SetExposure), then to the recorded one.
	// Changing it needs a recorded migration: without SchemaContent or
	// DryRun, a different exposure returns *UnrecordedExposureChangeError.
	Exposure *Exposure
}

// DeployedModelChangedError is returned by migrate when --if-deployed-checksum
// does not match the currently-deployed schema checksum: the database drifted
// from the expected state, so nothing was applied.
type DeployedModelChangedError struct {
	Expected string // checksum the caller expected to be deployed
	Actual   string // checksum actually deployed ("" when no migration is recorded)
}

func (e *DeployedModelChangedError) Error() string {
	actual := e.Actual
	if actual == "" {
		actual = "none (no migration recorded)"
	}
	return fmt.Sprintf("deployed model changed: expected checksum %s but database has %s; nothing was applied",
		e.Expected, actual)
}

// driftGuardError returns a *DeployedModelChangedError when expected is non-nil
// and does not match the deployed checksum (rec's checksum, or "" when rec is
// nil). It returns nil when the guard is unset or satisfied.
func driftGuardError(expected *string, rec *MigrationRecord) error {
	if expected == nil {
		return nil
	}
	deployed := ""
	if rec != nil {
		deployed = rec.SchemaChecksum
	}
	if deployed != *expected {
		return &DeployedModelChangedError{Expected: *expected, Actual: deployed}
	}
	return nil
}

// DatabaseAheadError is returned by migrate when the database's functions were
// generated by a newer melange than this one. Applying would replace them with
// older generated SQL, undoing codegen fixes, and during a rolling deploy old
// and new replicas would overwrite each other on every restart. Nothing is
// applied. Callers that run migrate on startup can treat it as "another
// replica already upgraded the database" (errors.As) and continue: the newer
// functions keep the same SQL API. MigrateOptions.Force overrides the guard.
type DatabaseAheadError struct {
	Deployed string // codegen version that generated the deployed functions
	Current  string // this melange's codegen version
}

func (e *DatabaseAheadError) Error() string {
	return fmt.Sprintf("database functions were generated by melange %s, newer than this melange (%s); "+
		"nothing was applied (upgrade melange, or force the migration to downgrade deliberately)",
		e.Deployed, e.Current)
}

// downgradeGuardError returns a *DatabaseAheadError when rec was written by a
// newer codegen version than this binary's. Versions that cannot be ordered
// pass: unstamped "dev" builds, bare commit hashes, and local `git describe`
// builds, which semver would misread as pre-releases of their base tag.
func downgradeGuardError(rec *MigrationRecord) error {
	if rec == nil || !CodegenVersionAhead(rec.CodegenVersion) {
		return nil
	}
	return &DatabaseAheadError{Deployed: rec.CodegenVersion, Current: CodegenVersion()}
}

// UnrecordedExposureChangeError is returned by a migration that records no
// migration (MigrateWithTypes, or MigrateWithTypesAndOptions without
// SchemaContent or DryRun) when asked for an exposure other than the one the
// database is known to have: the latest record's, or the default when none is
// recorded. Such a migration can neither drop the functions the previous
// exposure generated nor record the new one, so nothing is applied.
type UnrecordedExposureChangeError struct {
	Requested Exposure // the requested exposure, normalized
	Recorded  Exposure // the recorded exposure, normalized; the default when HasRecord is false
	HasRecord bool     // whether a migration is recorded
}

func (e *UnrecordedExposureChangeError) Error() string {
	recorded := fmt.Sprintf("the recorded exposure %s", exposureJSON(e.Recorded))
	if !e.HasRecord {
		recorded = fmt.Sprintf("the default exposure %s (no migration recorded)", exposureJSON(e.Recorded))
	}
	return fmt.Sprintf("requested exposure %s differs from %s; this migration records nothing, "+
		"so it could neither drop the previous exposure's functions nor record the new exposure, "+
		"and nothing was applied (change the exposure with migrator.MigrateWithOptions and MigrateOptions.Exposure, "+
		"Migrator.MigrateWithTypesAndOptions with SchemaContent (for an embedded schema, SchemaContent and "+
		"SchemaFormat: migrator.FormatSingle), or `melange migrate`)",
		exposureJSON(e.Requested), recorded)
}

// unrecordedExposureGuard returns an *UnrecordedExposureChangeError when a
// migration that records nothing is asked for an exposure other than rec's
// (the default when rec is nil). Nil keeps the recorded exposure and always
// passes. requested must already be validated (effectiveExposure):
// normalizing drops an invalid pattern next to "*".
func unrecordedExposureGuard(requested *Exposure, rec *MigrationRecord) error {
	if requested == nil {
		return nil
	}
	var recorded Exposure
	if rec != nil {
		recorded = rec.Exposure
	}
	if SameExposure(*requested, recorded) {
		return nil
	}
	return &UnrecordedExposureChangeError{
		Requested: requested.Normalized(),
		Recorded:  recorded.Normalized(),
		HasRecord: rec != nil,
	}
}

// CodegenVersionAhead reports whether deployed is a newer codegen version
// than this melange's, so migrate refuses to replace its functions unless
// forced (DatabaseAheadError). Versions that cannot be ordered are not
// ahead.
func CodegenVersionAhead(deployed string) bool {
	d, current := canonicalVersion(deployed), canonicalVersion(CodegenVersion())
	return orderable(d) && orderable(current) && semver.Compare(d, current) > 0
}

// gitDescribeSuffix matches what `git describe --tags --dirty` appends to a tag
// for local builds (`just build`): "-3-gabc1234", "-dirty", or both.
var gitDescribeSuffix = regexp.MustCompile(`(-\d+-g[0-9a-f]+)?(-dirty)?$`)

// orderable reports whether v is a version the downgrade guard can compare: a
// release, release candidate, or Go pseudo-version. A `git describe` build of
// v0.10.0 plus three commits is newer than v0.10.0, but semver orders the
// pre-release "v0.10.0-3-gabc1234" below it, so such builds are not compared.
func orderable(v string) bool {
	return semver.IsValid(v) && gitDescribeSuffix.FindString(semver.Canonical(v)) == ""
}

// canonicalVersion gives v the "v" prefix semver needs. Release binaries are
// stamped without it ("0.10.0"); go-install and library builds report it.
func canonicalVersion(v string) string {
	return "v" + strings.TrimPrefix(strings.TrimSpace(v), "v")
}

// SameCodegenVersion reports whether a and b name the same codegen version,
// ignoring the "v" prefix that only some build paths stamp.
func SameCodegenVersion(a, b string) bool {
	return canonicalVersion(a) == canonicalVersion(b)
}

// MigrationRecord represents a row in the melange_migrations table.
type MigrationRecord struct {
	// ID and MigratedAt identify the row and when it was written. Populated by
	// reads (getLastMigration); ignored on writes (the DB assigns them).
	ID         int
	MigratedAt time.Time

	MelangeVersion string
	SchemaChecksum string
	CodegenVersion string
	FunctionNames  []string
	// FunctionChecksums maps function_name → SHA256(sql_body) for each function
	// installed by this migration. Populated only when the database schema includes
	// the function_checksums column (added in v0.7.3). Nil on records written by
	// older versions; callers should treat nil as "no checksum data available" and
	// fall back to full-mode generation.
	FunctionChecksums map[string]string

	// SchemaDSL, SchemaFormat, and ModelJSON make the database self-describing.
	// They are populated only when the corresponding columns exist and were
	// written by a version that records the model. On older records SchemaDSL is
	// "" (treat as "no model recorded") and ModelJSON is nil.
	SchemaDSL    string
	SchemaFormat string
	ModelJSON    []byte

	// Exposure is the normalized exposure the functions were generated with.
	// Records written before the exposure column existed read as the default,
	// which is what those migrations generated.
	Exposure Exposure
}

// Migrator handles loading authorization schemas into PostgreSQL.
// The migrator is idempotent - safe to run on every application startup.
//
// The migration process:
//  1. Creates/replaces check_permission and list_accessible_* functions
//  2. Loads generated SQL entrypoints into the database
//
// # Usage
//
// Use the convenience functions in pkg/migrator for most use cases:
//
//	import "github.com/pthm/melange/pkg/migrator"
//	err := migrator.Migrate(ctx, db, "schemas/schema.fga")
//
// For embedded schemas (no file I/O):
//
//	err := migrator.MigrateFromString(ctx, db, schemaContent)
//
// Use the Migrator directly when you have pre-parsed TypeDefinitions
// or need fine-grained control (DDL-only, status checks, etc.):
//
//	types, _ := parser.ParseSchema("schemas/schema.fga")
//	m := migrator.NewMigrator(db, "schemas/schema.fga")
//	err := m.MigrateWithTypes(ctx, types)
//
// MigrateWithTypes records no migration, so it cannot change the SQL API
// exposure (see UnrecordedExposureChangeError). To record one from parsed
// types, pass the schema text as well:
//
//	err := m.MigrateWithTypesAndOptions(ctx, types, migrator.InternalMigrateOptions{
//		SchemaContent: schemaContent,
//		SchemaFormat:  migrator.FormatSingle,
//		Exposure:      &exposure,
//	})
type Migrator struct {
	db             Execer
	schemaPath     string
	databaseSchema string
	exposure       *Exposure
}

// NewMigrator creates a new schema migrator.
// The schemaPath should point to an OpenFGA DSL schema file (e.g., "schemas/schema.fga").
// The Execer is typically *sql.DB but can be *sql.Tx for testing.
func NewMigrator(db Execer, schemaPath string) *Migrator {
	return &Migrator{db: db, schemaPath: schemaPath, databaseSchema: "public"}
}

// SchemaPath returns the path to the schema file.
func (m *Migrator) SchemaPath() string {
	return m.schemaPath
}

// SetDatabaseSchema sets the PostgreSQL schema for melange objects.
func (m *Migrator) SetDatabaseSchema(databaseSchema string) {
	m.databaseSchema = databaseSchema
}

// DatabaseSchema returns the database schema.
func (m *Migrator) DatabaseSchema() string {
	return m.databaseSchema
}

// SetExposure sets the exposure MigrateWithTypesAndOptions uses when its
// options carry none, and the one MigrateWithTypes generates with. Nil, the
// initial value, keeps the exposure recorded by the last migration. It takes
// effect on calls that record a migration; a call that records nothing
// (MigrateWithTypes, or MigrateWithTypesAndOptions without SchemaContent or
// DryRun) may only restate the current exposure, and returns
// *UnrecordedExposureChangeError for any other.
func (m *Migrator) SetExposure(exposure *Exposure) {
	m.exposure = exposure
}

// requestedExposure returns the exposure the caller asked for: the options',
// else the Migrator's. Nil means keep the recorded one.
func (m *Migrator) requestedExposure(opt *Exposure) *Exposure {
	if opt != nil {
		return opt
	}
	return m.exposure
}

// effectiveExposure resolves a requested exposure against the latest record:
// the requested one when set, else the recorded one, else the default. The
// result is normalized, so it is exactly what the record will store. A
// requested exposure is validated as given: normalizing drops an Include that
// matches everything, invalid patterns in it included.
func effectiveExposure(requested *Exposure, rec *MigrationRecord) (Exposure, error) {
	switch {
	case requested != nil:
		if err := requested.Validate(); err != nil {
			return Exposure{}, fmt.Errorf("invalid exposure: %w", err)
		}
		return requested.Normalized(), nil
	case rec != nil:
		return rec.Exposure, nil
	default:
		return Exposure{}, nil
	}
}

// exposureJSON is the exposure as stored in melange_migrations.exposure: the
// normalized form as JSON, or '{}' for the default. Equal strings mean the
// same exposure, so it is the exposure part of the skip key.
func exposureJSON(e Exposure) string {
	n := e.Normalized()
	if n.IsDefault() {
		return "{}"
	}
	b, err := json.Marshal(n)
	if err != nil {
		// Exposure holds only strings and bools; marshaling cannot fail.
		panic(fmt.Sprintf("marshaling exposure: %v", err))
	}
	return string(b)
}

// SameExposure reports whether a and b select the same SQL API, that is,
// whether they normalize to the same exposure.
func SameExposure(a, b Exposure) bool {
	return exposureJSON(a) == exposureJSON(b)
}

// HasSchema returns true if the schema file exists.
// Use this to conditionally run migration or skip if not configured.
func (m *Migrator) HasSchema() bool {
	_, err := os.Stat(m.SchemaPath())
	return err == nil
}

