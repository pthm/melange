// GetStatus returns the current migration status.
// Useful for health checks or migration diagnostics.
func (m *Migrator) GetStatus(ctx context.Context) (*Status, error) {
	status := &Status{
		SchemaExists: m.HasSchema(),
	}

	// Check if melange_tuples relation exists (view, table, or materialized view)
	var tuplesExists bool
	err := m.db.QueryRowContext(ctx, fmt.Sprintf(
		`
			SELECT EXISTS (
				SELECT 1 FROM pg_class c
				JOIN pg_namespace n ON n.oid = c.relnamespace
				WHERE c.relname = 'melange_tuples'
				AND n.nspname = %s
				AND c.relkind IN ('r', 'v', 'm')
			)
		`,
		m.postgresSchema(),
	)).Scan(&tuplesExists)
	if err != nil {
		return nil, fmt.Errorf("checking melange_tuples: %w", err)
	}
	status.TuplesExists = tuplesExists

	return status, nil
}

// ComputeSchemaChecksum returns a SHA256 hash of the schema content.
// Used to detect schema changes for skip-if-unchanged optimization.
func ComputeSchemaChecksum(content string) string {
	h := sha256.Sum256([]byte(content))
	return hex.EncodeToString(h[:])
}

// ComputeFunctionChecksums computes SHA256 hashes for each named function's SQL body.
// The returned map is stored in the migration record and used by `generate migration --db`
// to determine which functions have changed and need to be included in the migration.
func ComputeFunctionChecksums(namedFunctions []NamedFunction) map[string]string {
	checksums := make(map[string]string, len(namedFunctions))
	for _, nf := range namedFunctions {
		h := sha256.Sum256([]byte(nf.SQL))
		checksums[nf.Name] = hex.EncodeToString(h[:])
	}
	return checksums
}

// GetLastMigration returns the most recent migration record, or nil if none
// exists. It queries against the migrator's own database connection, making it
// suitable for external callers such as the generate migration command.
//
// Internal migration code uses the private getLastMigration with an explicit
// Execer to participate in an in-progress transaction.
func (m *Migrator) GetLastMigration(ctx context.Context) (*MigrationRecord, error) {
	return m.getLastMigration(ctx, m.db)
}

// getLastMigration returns the most recent migration record, or nil if none exists.
//
// Optional columns (function_checksums, schema_dsl, schema_format, model_json)
// were added after the original DDL, so the SELECT is built from the columns
// that actually exist. This keeps reads compatible with databases migrated by
// any earlier version without a branch per column combination.
func (m *Migrator) getLastMigration(ctx context.Context, db Execer) (*MigrationRecord, error) {
	// First check if the migrations table exists
	tableExists, err := m.migrationTableExists(ctx, db)
	if err != nil {
		return nil, err
	}
	if !tableExists {
		return nil, nil // No migrations table yet
	}

	cols, err := m.migrationColumns(ctx, db)
	if err != nil {
		return nil, err
	}

	// id, migrated_at, and the original three columns are always present.
	// melange_version, function_checksums, and the model columns were each added
	// later, so probe for them; a database migrated by an old version that lacks
	// one must still read cleanly (status now depends on this).
	var (
		rec            MigrationRecord
		melangeVersion sql.NullString
		checksumsJSON  sql.NullString
		schemaDSL      sql.NullString
		schemaFormat   sql.NullString
		modelJSON      sql.NullString
		exposure       sql.NullString
	)
	selects := []string{"id", "migrated_at", "schema_checksum", "codegen_version", "function_names"}
	targets := []any{&rec.ID, &rec.MigratedAt, &rec.SchemaChecksum, &rec.CodegenVersion, pq.Array(&rec.FunctionNames)}
	if cols["melange_version"] {
		selects = append(selects, "melange_version")
		targets = append(targets, &melangeVersion)
	}
	if cols["function_checksums"] {
		selects = append(selects, "function_checksums::TEXT")
		targets = append(targets, &checksumsJSON)
	}
	if cols["schema_dsl"] {
		selects = append(selects, "schema_dsl")
		targets = append(targets, &schemaDSL)
	}
	if cols["schema_format"] {
		selects = append(selects, "schema_format")
		targets = append(targets, &schemaFormat)
	}
	if cols["model_json"] {
		selects = append(selects, "model_json::TEXT")
		targets = append(targets, &modelJSON)
	}
	if cols["exposure"] {
		selects = append(selects, "exposure::TEXT")
		targets = append(targets, &exposure)
	}

	query := fmt.Sprintf("SELECT %s FROM %s ORDER BY id DESC LIMIT 1",
		strings.Join(selects, ", "), m.prefixIdent("melange_migrations"))
	err = db.QueryRowContext(ctx, query).Scan(targets...)
	if err == sql.ErrNoRows {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("querying last migration: %w", err)
	}

	if checksumsJSON.Valid && checksumsJSON.String != "" {
		rec.FunctionChecksums = make(map[string]string)
		if err := json.Unmarshal([]byte(checksumsJSON.String), &rec.FunctionChecksums); err != nil {
			return nil, fmt.Errorf("unmarshaling function checksums: %w", err)
		}
	}
	rec.MelangeVersion = melangeVersion.String
	rec.SchemaDSL = schemaDSL.String
	rec.SchemaFormat = schemaFormat.String
	if modelJSON.Valid && modelJSON.String != "" && modelJSON.String != "{}" {
		rec.ModelJSON = []byte(modelJSON.String)
	}
	if rec.Exposure, err = decodeExposure(exposure); err != nil {
		return nil, err
	}
	return &rec, nil
}

// decodeExposure reads a melange_migrations.exposure value. NULL (the column
// is absent) and '{}' are the default exposure.
func decodeExposure(v sql.NullString) (Exposure, error) {
	var e Exposure
	if !v.Valid || v.String == "" {
		return e, nil
	}
	if err := json.Unmarshal([]byte(v.String), &e); err != nil {
		return Exposure{}, fmt.Errorf("unmarshaling recorded exposure: %w", err)
	}
	return e.Normalized(), nil
}

// migrationTableExists reports whether the melange_migrations table exists in
// the configured schema. Used to distinguish an un-migrated database from one
// whose columns are merely hidden by privileges (which would make an
// information_schema probe misleadingly return nothing).
func (m *Migrator) migrationTableExists(ctx context.Context, db Execer) (bool, error) {
	var exists bool
	err := db.QueryRowContext(ctx, fmt.Sprintf(
		`
			SELECT EXISTS (
				SELECT 1 FROM pg_class c
				JOIN pg_namespace n ON n.oid = c.relnamespace
				WHERE c.relname = 'melange_migrations'
				AND n.nspname = %s
			)
		`,
		m.postgresSchema(),
	)).Scan(&exists)
	if err != nil {
		return false, fmt.Errorf("checking melange_migrations table: %w", err)
	}
	return exists, nil
}

// lockMigrations takes a transaction-scoped advisory lock that serializes
// migrations against this Postgres schema, released when db's transaction
// ends. The two-key form keeps melange's locks apart from an application's
// own single-key advisory locks. Replicas running migrate on startup otherwise race on the tracking
// table DDL and on CREATE OR REPLACE FUNCTION. It only serializes when db is a
// transaction; on an autocommit Execer the lock is released at once.
func (m *Migrator) lockMigrations(ctx context.Context, db Execer) error {
	_, err := db.ExecContext(ctx,
		`SELECT pg_advisory_xact_lock(hashtext('melange'), hashtext(COALESCE(NULLIF($1, ''), current_schema())))`,
		m.databaseSchema)
	if err != nil {
		return fmt.Errorf("acquiring migration lock: %w", err)
	}
	return nil
}

// driftGuardInTx re-evaluates the drift guard against the latest record visible
// to db (a transaction). Read-committed visibility means a migration committed
// since the up-front check is seen here, so a concurrent change that lands while
// this migration applies is caught before the record is written.
func (m *Migrator) driftGuardInTx(ctx context.Context, db Execer, expected *string) error {
	if expected == nil {
		return nil
	}
	rec, err := m.getLastMigration(ctx, db)
	if err != nil {
		return err
	}
	return driftGuardError(expected, rec)
}

// migrationColumns returns the set of column names present in the
// melange_migrations table, used to build a compatible SELECT.
func (m *Migrator) migrationColumns(ctx context.Context, db Execer) (map[string]bool, error) {
	rows, err := db.QueryContext(ctx, fmt.Sprintf(
		`
			SELECT column_name FROM information_schema.columns
			WHERE table_name = 'melange_migrations'
			AND table_schema = %s
		`,
		m.postgresSchema(),
	))
	if err != nil {
		return nil, fmt.Errorf("listing melange_migrations columns: %w", err)
	}
	defer func() { _ = rows.Close() }()

	cols := make(map[string]bool)
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, fmt.Errorf("scanning column name: %w", err)
		}
		cols[name] = true
	}
	return cols, rows.Err()
}

// DeployedModel is the authorization model recorded by the most recent
// migration — the source for `melange schema pull`, drift detection, and diffs.
type DeployedModel struct {
	DSL            string                  // OpenFGA DSL that produced the deployment
	Format         string                  // "single" or "modular"
	Types          []schema.TypeDefinition // parsed model (see DeployedTypes)
	SchemaChecksum string
	MelangeVersion string
	CodegenVersion string // codegen version that generated the installed functions
	MigratedAt     time.Time
	Exposure       Exposure // normalized SQL API exposure; zero is the default
}

// GetDeployedModel returns the model recorded by the most recent migration, or
// nil if none has been recorded — either because the database has never been
// migrated or because it was migrated before model storage existed (SchemaDSL
// empty). Callers surface a "re-run migrate to record the model" hint for nil.
// Types comes from DeployedTypes, so a record with only the DSL has them too;
// it is nil when neither the JSON nor the DSL yields a model, which leaves
// the DSL available (schema pull) without failing.
func (m *Migrator) GetDeployedModel(ctx context.Context) (*DeployedModel, error) {
	rec, err := m.GetLastMigration(ctx)
	if err != nil {
		return nil, err
	}
	if rec == nil || rec.SchemaDSL == "" {
		return nil, nil
	}
	types, err := DeployedTypes(rec)
	if err != nil {
		types = nil
	}
	return &DeployedModel{
		DSL:            rec.SchemaDSL,
		Format:         rec.SchemaFormat,
		Types:          types,
		SchemaChecksum: rec.SchemaChecksum,
		MelangeVersion: rec.MelangeVersion,
		CodegenVersion: rec.CodegenVersion,
		MigratedAt:     rec.MigratedAt,
		Exposure:       rec.Exposure,
	}, nil
}

// DeployedTypes returns the parsed model a migration record stores,
// preferring model_json and falling back to parsing the recorded DSL when the
// JSON is absent, empty or unreadable, the same order doctor uses, so every
// tool agrees on what a database has deployed.
//
// It returns nil types and a nil error for a record written before model
// storage (no DSL recorded), which callers report as "not recorded".
func DeployedTypes(rec *MigrationRecord) ([]schema.TypeDefinition, error) {
	if rec == nil || rec.SchemaDSL == "" {
		return nil, nil
	}
	if types, err := schema.UnmarshalModel(rec.ModelJSON); err == nil && len(types) > 0 {
		return types, nil
	}
	types, err := parser.ParseRecordedSchemaString(rec.SchemaDSL)
	if err != nil {
		return nil, fmt.Errorf("parsing recorded schema DSL: %w", err)
	}
	return types, nil
}

// GetMigrationHistory returns up to limit migration records, most recent first.
// It reads a lightweight subset (no DSL or model JSON) suitable for an audit
// listing, and tolerates databases migrated by older versions that lack the
// melange_version, schema_format or exposure columns. Returns nil when no
// migrations table exists.
func (m *Migrator) GetMigrationHistory(ctx context.Context, limit int) ([]MigrationRecord, error) {
	if limit < 1 {
		return nil, fmt.Errorf("limit must be at least 1, got %d", limit)
	}
	exists, err := m.migrationTableExists(ctx, m.db)
	if err != nil {
		return nil, err
	}
	if !exists {
		return nil, nil
	}
	cols, err := m.migrationColumns(ctx, m.db)
	if err != nil {
		return nil, err
	}

	selects := []string{"id", "migrated_at", "schema_checksum", "codegen_version", "function_names"}
	hasVersion := cols["melange_version"]
	hasFormat := cols["schema_format"]
	hasExposure := cols["exposure"]
	if hasVersion {
		selects = append(selects, "melange_version")
	}
	if hasFormat {
		selects = append(selects, "schema_format")
	}
	if hasExposure {
		selects = append(selects, "exposure::TEXT")
	}

	query := fmt.Sprintf("SELECT %s FROM %s ORDER BY id DESC LIMIT $1",
		strings.Join(selects, ", "), m.prefixIdent("melange_migrations"))
	rows, err := m.db.QueryContext(ctx, query, limit)
	if err != nil {
		return nil, fmt.Errorf("querying migration history: %w", err)
	}
	defer func() { _ = rows.Close() }()

	var history []MigrationRecord
	for rows.Next() {
		var (
			rec                          MigrationRecord
			melangeVer, format, exposure sql.NullString
		)
		targets := []any{&rec.ID, &rec.MigratedAt, &rec.SchemaChecksum, &rec.CodegenVersion, pq.Array(&rec.FunctionNames)}
		if hasVersion {
			targets = append(targets, &melangeVer)
		}
		if hasFormat {
			targets = append(targets, &format)
		}
		if hasExposure {
			targets = append(targets, &exposure)
		}
		if err := rows.Scan(targets...); err != nil {
			return nil, fmt.Errorf("scanning migration row: %w", err)
		}
		rec.MelangeVersion = melangeVer.String
		rec.SchemaFormat = format.String
		if rec.Exposure, err = decodeExposure(exposure); err != nil {
			return nil, err
		}
		history = append(history, rec)
	}
	return history, rows.Err()
}

// migrationRecordMatches reports whether the last migration was recorded with
// the same schema checksum, codegen version and exposure (exposureJSON) as
// the current run. Every skip decision goes through it, so an exposure-only
// change is applied and recorded rather than skipped.
//
// A record written before model storage existed (SchemaDSL empty) never
// matches: falling through lets phase 2 backfill schema_dsl/model_json without
// re-applying the generated functions, so a plain rerun after upgrading makes
// GetDeployedModel / schema pull work without --force.
func migrationRecordMatches(lastMigration *MigrationRecord, schemaChecksum, exposure string) bool {
	if lastMigration == nil {
		return false
	}
	return lastMigration.SchemaChecksum == schemaChecksum &&
		SameCodegenVersion(lastMigration.CodegenVersion, CodegenVersion()) &&
		exposureJSON(lastMigration.Exposure) == exposure &&
		lastMigration.SchemaDSL != ""
}

// shouldSkipMigration returns true if the schema, codegen version and exposure
// are unchanged.
// This is the fast-path (phase 1) skip: no SQL generation needed at all.
//
// Unstamped "dev" builds never skip here: "dev" is a constant, so a rebuilt
// binary with changed codegen would look identical to the last migration.
// Falling through lets the phase 2 checksum comparison (which includes
// dispatchers) decide. Released binaries and go-install/library builds report a
// real version (lib/version resolves it from ldflags or embedded build info),
// so they still get the fast-path skip.
func shouldSkipMigration(lastMigration *MigrationRecord, schemaChecksum, exposure string) bool {
	if CodegenVersion() == "dev" {
		return false
	}
	return migrationRecordMatches(lastMigration, schemaChecksum, exposure)
}

// shouldSkipApply returns true if the generated SQL is identical to what was
// last applied. This is the phase 2 skip: SQL was generated (because the schema
// or melange version changed) but the output is byte-for-byte identical, so
// there is nothing to apply. Returns true only when there are no orphaned
// functions and every function checksum matches.
func shouldSkipApply(lastMigration *MigrationRecord, currentChecksums map[string]string, expectedFunctions []string) bool {
	if lastMigration == nil || lastMigration.FunctionChecksums == nil {
		return false
	}

	// Check for orphaned functions (present in previous but not in current)
	currentSet := make(map[string]bool, len(expectedFunctions))
	for _, fn := range expectedFunctions {
		currentSet[fn] = true
	}
	for _, fn := range lastMigration.FunctionNames {
		if !currentSet[fn] {
			return false // Orphan exists, must apply
		}
	}

	// Check that every current function has an unchanged checksum
	for name, checksum := range currentChecksums {
		prevChecksum, existed := lastMigration.FunctionChecksums[name]
		if !existed || prevChecksum != checksum {
			return false // New or changed function, must apply
		}
	}

	return true
}

// PlanAction is what an unforced migration would do; see Migrator.Plan.
type PlanAction string

const (
	// PlanApply applies every generated function, drops the orphans and
	// records the migration (when it has the schema text to record).
	PlanApply PlanAction = "apply"
	// PlanRecordOnly records the migration and applies nothing: the
	// generated SQL is the SQL the last migration recorded (phase 2).
	PlanRecordOnly PlanAction = "record_only"
	// PlanSkip does nothing: the schema, codegen version and exposure match
	// the last migration (phase 1), or the generated SQL and the record both
	// do (phase 2).
	PlanSkip PlanAction = "skip"
	// PlanRefusedAhead applies nothing and returns *DatabaseAheadError: a
	// newer melange migrated the database.
	PlanRefusedAhead PlanAction = "refused_ahead"
)

// OrphanedFunction is an installed function an applying migration drops,
// with the objects that depend on it (as FunctionDependent.Object names
// them). An unforced migration refuses to drop one with dependents
// (*DependentObjectsError); a forced one drops them with CASCADE.
type OrphanedFunction struct {
	Name       string
	Dependents []string
}

// MigrationPlan predicts an unforced migration; see Migrator.Plan.
type MigrationPlan struct {
	Action PlanAction

	// Record is the last migration, nil when none is recorded.
	Record *MigrationRecord

	// Exposure is the exposure the migration generates with: the requested
	// one, else the recorded one, else the default. Unset for
	// PlanRefusedAhead.
	Exposure Exposure

	// Orphans are what an applying migration drops: installed functions that
	// any migration recorded and this one does not generate. Filled for every
	// action but PlanRefusedAhead, since a forced migration applies, and drops
	// them, whatever the action.
	Orphans []OrphanedFunction
}

// planAction decides what an unforced migration does once the downgrade
// guard has passed or not: refuse a database a newer melange migrated, skip
// (phase 1, or phase 2 with a matching record), record only (phase 2), or
// apply. key is exposureJSON of the exposure c was generated with. Without
// a schema checksum the migration records nothing and always applies.
// migrateOnce and Plan both decide through it.
func planAction(rec *MigrationRecord, checksum, key string, c compiled) PlanAction {
	switch {
	case downgradeGuardError(rec) != nil:
		return PlanRefusedAhead
	case checksum == "":
		return PlanApply
	case shouldSkipMigration(rec, checksum, key):
		return PlanSkip
	case !shouldSkipApply(rec, c.checksums, c.names):
		return PlanApply
	case migrationRecordMatches(rec, checksum, key):
		return PlanSkip
	default:
		return PlanRecordOnly
	}
}

// Plan predicts what MigrateWithTypesAndOptions would do with opts unforced,
// without changing the database or taking the migration lock: the action,
// and the orphans an applying (or forced) run drops, with their dependents.
// opts.Force and opts.DryRun are ignored, and opts.IfDeployedChecksum is not
// evaluated. It returns the error the migration would fail with before
// applying anything (a cycle, an invalid exposure, or
// *UnrecordedExposureChangeError without opts.SchemaContent), except that a
// database a newer melange migrated is PlanRefusedAhead.
//
// A migration that commits between Plan and the run can change the outcome.
// A readiness check can wait for PlanSkip: the database then has exactly what
// this schema, exposure and codegen version generate, as recorded.
func (m *Migrator) Plan(ctx context.Context, types []TypeDefinition, opts InternalMigrateOptions) (*MigrationPlan, error) {
	if err := DetectCycles(types); err != nil {
		return nil, err
	}
	rec, err := m.getLastMigration(ctx, m.db)
	if err != nil {
		return nil, fmt.Errorf("checking last migration: %w", err)
	}
	plan := &MigrationPlan{Record: rec}
	if downgradeGuardError(rec) != nil {
		plan.Action = PlanRefusedAhead
		return plan, nil
	}
	requested := m.requestedExposure(opts.Exposure)
	if plan.Exposure, err = effectiveExposure(requested, rec); err != nil {
		return nil, err
	}
	var checksum string
	if opts.SchemaContent != "" {
		checksum = ComputeSchemaChecksum(opts.SchemaContent)
	} else if err := unrecordedExposureGuard(requested, rec); err != nil {
		return nil, err
	}
	c, err := m.compile(types, plan.Exposure)
	if err != nil {
		return nil, err
	}
	drops, err := m.dryRunDrops(ctx, c.names, false)
	if err != nil {
		return nil, err
	}
	for _, d := range drops {
		plan.Orphans = append(plan.Orphans, OrphanedFunction{Name: d.Function, Dependents: d.Dependents})
	}
	plan.Action = planAction(rec, checksum, exposureJSON(plan.Exposure), c)
	return plan, nil
}

// GeneratedFunctionFilter matches pg_proc rows (aliased p) named like a
// per-relation function melange generates: check_, list_, expand_, explain_,
// accessible_ or accessiblesk_.
// Migrate's orphan cleanup and doctor's orphan report share it so a new family
// can't be missed by one of them.
const GeneratedFunctionFilter = `p.proname ~ '^(check|list|expand|explain|accessible|accessiblesk)_'`

// getCurrentFunctions returns the installed functions that orphan cleanup may
// drop: those matching GeneratedFunctionFilter that a previous migration
// recorded, so a user's own function that merely shares a prefix (say
// explain_invoice) is never dropped.
func (m *Migrator) getCurrentFunctions(ctx context.Context, db Execer) ([]string, error) {
	rows, err := db.QueryContext(ctx, fmt.Sprintf(`
		SELECT p.proname
		FROM pg_proc p
		JOIN pg_namespace n ON p.pronamespace = n.oid
		WHERE n.nspname = %s
		AND %s
		AND p.proname IN (SELECT unnest(function_names) FROM %s)
	`, m.postgresSchema(), GeneratedFunctionFilter, m.prefixIdent("melange_migrations")))
	if err != nil {
		return nil, fmt.Errorf("querying pg_proc: %w", err)
	}
	defer func() { _ = rows.Close() }()

	functions := make([]string, 0, 32)
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, fmt.Errorf("scanning function name: %w", err)
		}
		functions = append(functions, name)
	}
	return functions, rows.Err()
}

// orphanedFunctions returns the installed functions orphan cleanup may drop
// (see getCurrentFunctions) that expected no longer names, in pg_proc order.
func (m *Migrator) orphanedFunctions(ctx context.Context, db Execer, expected []string) ([]string, error) {
	current, err := m.getCurrentFunctions(ctx, db)
	if err != nil {
		return nil, fmt.Errorf("getting current functions: %w", err)
	}
	keep := make(map[string]bool, len(expected))
	for _, fn := range expected {
		keep[fn] = true
	}
	var orphans []string
	for _, fn := range current {
		if !keep[fn] {
			orphans = append(orphans, fn)
		}
	}
	return orphans, nil
}

// FunctionDependent is a database object that depends on a generated
// function, as recorded in pg_depend: a view or materialized view, an RLS
// policy, a rule, or a function with a SQL-standard (BEGIN ATOMIC) body.
type FunctionDependent struct {
	Function string // the generated function
	Object   string // the dependent, as pg_describe_object names it (e.g. "view doc_access")
}

// DependentObjectsError is returned by migrate when functions the new SQL no
// longer generates (orphans) have dependents. Dropping them with CASCADE
// would silently drop the dependents too; losing an RLS policy widens access.
// MigrateOptions.Force drops them.
//
// Migrate checks for dependents before applying anything. A dependent created
// by another session after that check makes the drop itself fail, since an
// unforced drop does not CASCADE; Err then holds the database's refusal
// (SQLSTATE 2BP01) and the migration is not recorded. In the migrator's own
// transaction everything is rolled back; on a caller's Execer without one,
// the new functions stay applied and the orphans stay installed.
type DependentObjectsError struct {
	Dependents []FunctionDependent
	Err        error

	function string // the function whose drop was refused, when Err is set
}

// withDependents fills in the dependents of a drop refused in the migrator's
// own transaction, once that transaction has been rolled back and released
// its connection. Other errors are returned unchanged.
func (m *Migrator) withDependents(ctx context.Context, err error) error {
	var depErr *DependentObjectsError
	if errors.As(err, &depErr) && depErr.function != "" && len(depErr.Dependents) == 0 {
		depErr.Dependents, _ = m.functionDependents(ctx, m.db, []string{depErr.function})
	}
	return err
}

func (e *DependentObjectsError) Error() string {
	var b strings.Builder
	if e.Err == nil {
		b.WriteString("migration would drop functions that other database objects depend on; nothing was applied")
	} else {
		b.WriteString("migration was refused dropping functions that other database objects now depend on; it was not recorded")
	}
	b.WriteString(" (remove or change the dependents, or force the migration to drop them with CASCADE):")
	for _, d := range e.Dependents {
		fmt.Fprintf(&b, "\n  %s depends on %s", d.Object, d.Function)
	}
	if e.Err != nil && len(e.Dependents) == 0 {
		fmt.Fprintf(&b, "\n  %v", e.Err)
	}
	return b.String()
}

func (e *DependentObjectsError) Unwrap() error { return e.Err }

// functionDependents returns the objects that depend on any of functions,
// other than those functions themselves. A view depends on its functions
// through its _RETURN rule, so it is reported as the view.
func (m *Migrator) functionDependents(ctx context.Context, db Execer, functions []string) ([]FunctionDependent, error) {
	if len(functions) == 0 {
		return nil, nil
	}
	rows, err := db.QueryContext(ctx, m.functionDependentsQuery("$1"), pq.Array(functions))
	if err != nil {
		return nil, fmt.Errorf("querying function dependents: %w", err)
	}
	defer func() { _ = rows.Close() }()

	var deps []FunctionDependent
	for rows.Next() {
		var d FunctionDependent
		if err := rows.Scan(&d.Function, &d.Object); err != nil {
			return nil, fmt.Errorf("scanning function dependent: %w", err)
		}
		deps = append(deps, d)
	}
	return deps, rows.Err()
}

// functionDependentsQuery selects (function, dependent) for the functions
// named by the TEXT[] expression names; see functionDependents.
func (m *Migrator) functionDependentsQuery(names string) string {
	return fmt.Sprintf(`
		SELECT DISTINCT p.proname,
			CASE
				WHEN r.rulename = '_RETURN' THEN pg_describe_object('pg_class'::regclass, r.ev_class, 0)
				ELSE pg_describe_object(d.classid, d.objid, d.objsubid)
			END
		FROM pg_depend d
		JOIN pg_proc p ON p.oid = d.refobjid
		JOIN pg_namespace n ON n.oid = p.pronamespace
		LEFT JOIN pg_rewrite r ON d.classid = 'pg_rewrite'::regclass AND r.oid = d.objid
		WHERE d.refclassid = 'pg_proc'::regclass
		AND d.deptype IN ('n', 'a')
		AND n.nspname = %[1]s
		AND p.proname = ANY(%[2]s)
		AND NOT (d.classid = 'pg_proc'::regclass AND d.objid IN (
			SELECT o.oid FROM pg_proc o WHERE o.pronamespace = n.oid AND o.proname = ANY(%[2]s)))
		ORDER BY 1, 2
	`, m.postgresSchema(), names)
}

// refuseDependents returns a *DependentObjectsError when any of orphans has
// dependents, unless force is set.
func (m *Migrator) refuseDependents(ctx context.Context, db Execer, orphans []string, force bool) error {
	if force {
		return nil
	}
	deps, err := m.functionDependents(ctx, db, orphans)
	if err != nil {
		return err
	}
	if len(deps) > 0 {
		return &DependentObjectsError{Dependents: deps}
	}
	return nil
}

// sqlStateDependentObjectsStillExist is raised by a DROP without CASCADE
// that other objects depend on.
const sqlStateDependentObjectsStillExist = "2BP01"

// dropFunctions drops the named functions, with CASCADE only when forced.
// Callers check dependents first (refuseDependents), but that is a snapshot:
// another session can create a dependent before the drop, and recording one
// takes no lock on the function. Without CASCADE the database refuses such a
// drop, reported as a *DependentObjectsError. The dependents are read through
// db unless inTx: the failure aborts that transaction, and a lookup through
// the pool could wait for the connection it holds, so the caller reads them
// after rolling back (see withDependents). Melange's functions have string
// bodies with no pg_depend edges between them, so they never block each
// other's drop.
func (m *Migrator) dropFunctions(ctx context.Context, db Execer, inTx bool, functions []string, force bool) error {
	for _, fn := range functions {
		_, err := db.ExecContext(ctx, m.dropFunctionSQL(fn, force))
		var state interface{ SQLState() string }
		if errors.As(err, &state) && state.SQLState() == sqlStateDependentObjectsStillExist {
			depErr := &DependentObjectsError{Err: err, function: fn}
			if !inTx {
				// Best effort: on a caller's transaction the lookup fails too,
				// and the database's message is reported instead.
				depErr.Dependents, _ = m.functionDependents(ctx, db, []string{fn})
			}
			return depErr
		}
		if err != nil {
			return fmt.Errorf("dropping orphaned function %s: %w", fn, err)
		}
	}
	return nil
}

// dropFunctionSQL is the statement that drops an orphaned function, shared by
// migrate and the dry-run script so both drop it the same way.
func (m *Migrator) dropFunctionSQL(fn string, cascade bool) string {
	stmt := "DROP FUNCTION IF EXISTS " + m.prefixIdent(fn)
	if cascade {
		stmt += " CASCADE"
	}
	return stmt
}

// applyMigrationsDDL creates the melange_migrations table if it doesn't exist.
// Also applies any necessary column migrations for existing tables.
func (m *Migrator) applyMigrationsDDL(ctx context.Context, db Execer) error {
	for _, stmt := range migrationsTableDDL(m.databaseSchema) {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("applying migrations DDL: %w", err)
		}
	}
	return nil
}

// migrationWrite carries the fields persisted to a new melange_migrations row.
type migrationWrite struct {
	MelangeVersion    string
	SchemaChecksum    string
	FunctionNames     []string
	FunctionChecksums map[string]string
	SchemaDSL         string
	SchemaFormat      string
	ModelJSON         []byte
	Exposure          string // exposureJSON of the exposure generated with
}

// modelJSONOrEmpty returns the model JSON, substituting an empty JSON object for
// the NOT NULL model_json column when no model was captured (e.g. embedded-string
// migrations without content).
func (w migrationWrite) modelJSONOrEmpty() []byte {
	if len(w.ModelJSON) == 0 {
		return []byte("{}")
	}
	return w.ModelJSON
}

// exposureOrDefault returns the exposure JSON, '{}' (the default) when unset.
func (w migrationWrite) exposureOrDefault() string {
	if w.Exposure == "" {
		return "{}"
	}
	return w.Exposure
}

// errDeployedFunctionsChanged reports that the deployed functions no longer
// match this migration's generated SQL once the lock is held, so recording
// without applying is unsafe and the full apply path must run instead.
var errDeployedFunctionsChanged = errors.New("deployed functions changed while waiting for the migration lock")

// errRecordedExposureChanged reports that a run keeping the recorded exposure
// generated under one exposure, but a migration committed while it waited
// for the lock recorded another. Applying would revert that migration's
// exposure, so the run starts over against the new record.
var errRecordedExposureChanged = errors.New("recorded exposure changed while waiting for the migration lock")

// inheritedExposureGuard returns errRecordedExposureChanged when requested is
// nil (keep the recorded exposure) and rec no longer records generated, the
// exposure this run generated with.
func inheritedExposureGuard(requested *Exposure, rec *MigrationRecord, generated string) error {
	if requested != nil {
		return nil
	}
	var recorded Exposure
	if rec != nil {
		recorded = rec.Exposure
	}
	if exposureJSON(recorded) != generated {
		return errRecordedExposureChanged
	}
	return nil
}

// recordMigrationOnly inserts a migration record without re-applying functions.
// Used when phase 2 skip determines the generated SQL is identical to what's
// already installed — only the melange version or schema checksum changed.
// Under the migration lock it re-reads the latest record: the downgrade and
// drift guards are re-verified, like the full apply path; a concurrent run that
// already recorded the same state makes this a no-op (skipped); and if the
// deployed functions no longer match, it returns errDeployedFunctionsChanged.
func (m *Migrator) recordMigrationOnly(ctx context.Context, w migrationWrite, ifDeployed *string, requested *Exposure) (skipped bool, err error) {
	record := func(db Execer) (bool, error) {
		if err := m.lockMigrations(ctx, db); err != nil {
			return false, err
		}
		if err := m.applyMigrationsDDL(ctx, db); err != nil {
			return false, err
		}
		rec, err := m.getLastMigration(ctx, db)
		if err != nil {
			return false, fmt.Errorf("checking last migration: %w", err)
		}
		if err := downgradeGuardError(rec); err != nil {
			return false, err
		}
		if err := driftGuardError(ifDeployed, rec); err != nil {
			return false, err
		}
		if err := inheritedExposureGuard(requested, rec, w.Exposure); err != nil {
			return false, err
		}
		// A concurrent migration may have deployed different SQL while this
		// one waited; recording without applying would then misdescribe it.
		if !shouldSkipApply(rec, w.FunctionChecksums, w.FunctionNames) {
			return false, errDeployedFunctionsChanged
		}
		if migrationRecordMatches(rec, w.SchemaChecksum, w.Exposure) {
			return true, nil
		}
		return false, m.insertMigrationRecord(ctx, db, w)
	}

	if txer, ok := m.db.(interface {
		BeginTx(ctx context.Context, opts *sql.TxOptions) (*sql.Tx, error)
	}); ok {
		tx, err := txer.BeginTx(ctx, nil)
		if err != nil {
			return false, fmt.Errorf("starting transaction: %w", err)
		}
		defer func() { _ = tx.Rollback() }()
		if skipped, err := record(tx); err != nil || skipped {
			return skipped, err
		}
		return false, tx.Commit()
	}
	return record(m.db)
}

// insertMigrationRecord records the migration in melange_migrations.
func (m *Migrator) insertMigrationRecord(ctx context.Context, db Execer, w migrationWrite) error {
	checksumsJSON, err := json.Marshal(w.FunctionChecksums)
	if err != nil {
		return fmt.Errorf("marshaling function checksums: %w", err)
	}
	_, err = db.ExecContext(ctx, fmt.Sprintf(
		`
			INSERT INTO %s (melange_version, schema_checksum, codegen_version, function_names, function_checksums, schema_dsl, schema_format, model_json, exposure)
			VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
		`,
		m.prefixIdent("melange_migrations"),
	), w.MelangeVersion, w.SchemaChecksum, CodegenVersion(), pq.Array(w.FunctionNames), string(checksumsJSON),
		w.SchemaDSL, w.SchemaFormat, string(w.modelJSONOrEmpty()), w.exposureOrDefault())
	if err != nil {
		return fmt.Errorf("inserting migration record: %w", err)
	}
	return nil
}

// MigrateWithTypesAndOptions performs database migration with options.
// This is the full-featured migration method that supports dry-run, two-phase
// skip detection, and orphan cleanup.
//
// Skip detection has two phases:
//   - Phase 1: If the schema checksum, melange version and exposure all match
//     the last migration, skip entirely without generating SQL.
//   - Phase 2: If phase 1 didn't skip (schema, version or exposure changed),
//     generate the SQL and compare function checksums against the last
//     migration. If every function is identical and no orphans exist, skip
//     applying and only record the new migration state.
//
// Orphaned functions (installed by the previous migration, no longer
// generated) are dropped. When user objects depend on one (see
// FunctionDependent), migration fails with *DependentObjectsError and applies
// nothing, unless opts.Force is set, which drops them with CASCADE.
//
// Without opts.SchemaContent there is no checksum to record: it applies on
// every run, drops the orphans of the latest existing record, records
// nothing, and refuses an exposure change with
// *UnrecordedExposureChangeError. Pass the schema text (for an embedded
// schema, with SchemaFormat FormatSingle) to record the migration.
//
// See MigrateWithTypes for basic usage without options.
func (m *Migrator) MigrateWithTypesAndOptions(ctx context.Context, types []TypeDefinition, opts InternalMigrateOptions) error {
	_, err := m.migrateWithTypesAndOptions(ctx, types, opts)
	return err
}

// maxMigrateAttempts bounds how often a run that keeps the recorded exposure
// starts over because a concurrent migration recorded another one.
const maxMigrateAttempts = 3

// migrateWithTypesAndOptions implements MigrateWithTypesAndOptions and
// additionally reports whether the migration was a no-op (both skip phases
// count; recording a new migration state does not).
func (m *Migrator) migrateWithTypesAndOptions(ctx context.Context, types []TypeDefinition, opts InternalMigrateOptions) (skipped bool, err error) {
	for attempt := 1; ; attempt++ {
		skipped, err = m.migrateOnce(ctx, types, opts)
		if !errors.Is(err, errRecordedExposureChanged) || attempt == maxMigrateAttempts {
			return skipped, err
		}
	}
}

// migrateOnce is one attempt of migrateWithTypesAndOptions.
func (m *Migrator) migrateOnce(ctx context.Context, types []TypeDefinition, opts InternalMigrateOptions) (skipped bool, err error) {
	// 1. Validate schema before any computation
	if err := DetectCycles(types); err != nil {
		return false, err
	}

	// 2. Compute schema checksum if content provided
	var schemaChecksum string
	if opts.SchemaContent != "" {
		schemaChecksum = ComputeSchemaChecksum(opts.SchemaContent)
	}

	// On a caller-owned transaction (an Execer without BeginTx), every read
	// below holds its table locks until the caller commits. Take the migration
	// lock first, or two such callers deadlock: each holds a read lock on the
	// tracking table that the other's DDL waits for. Re-taking it later in the
	// same transaction is a no-op.
	if _, ownTx := m.db.(interface {
		BeginTx(ctx context.Context, opts *sql.TxOptions) (*sql.Tx, error)
	}); !ownTx && opts.DryRun == nil {
		if err := m.lockMigrations(ctx, m.db); err != nil {
			return false, err
		}
	}

	// 3. Fetch last migration record (needed for the drift and downgrade
	// guards, both skip phases, the exposure when none was requested, and the
	// exposure guard of a run that records nothing). The drift guard needs it
	// even under --force and --dry-run. A dry-run script records the
	// migration, so it counts as recording.
	requested := m.requestedExposure(opts.Exposure)
	records := opts.SchemaContent != "" || opts.DryRun != nil
	var lastMigration *MigrationRecord
	if opts.IfDeployedChecksum != nil || requested == nil || !records || (!opts.Force && opts.DryRun == nil) {
		lastMigration, err = m.getLastMigration(ctx, m.db)
		if err != nil {
			return false, fmt.Errorf("checking last migration: %w", err)
		}
	}

	// Drift guard: --if-deployed-checksum makes migrate a compare-and-swap. Abort
	// early if the database isn't at the expected checksum — including in dry-run,
	// so a drift-gated preview fails rather than printing SQL against a drifted
	// database. The apply path re-checks inside its transaction (see below) to
	// catch drift committed while this migration runs.
	if err := driftGuardError(opts.IfDeployedChecksum, lastMigration); err != nil {
		return false, err
	}

	// Downgrade guard: refuse to replace functions generated by a newer melange.
	// Checked up front for a fast, side-effect-free refusal, and again under the
	// migration lock. Dry-run only prints SQL, so it is not guarded.
	if !opts.Force && opts.DryRun == nil {
		if err := downgradeGuardError(lastMigration); err != nil {
			return false, err
		}
	}

	exposure, err := effectiveExposure(requested, lastMigration)
	if err != nil {
		return false, err
	}
	// Without a record to write, the run can neither drop the previous
	// exposure's functions nor record a new exposure: refuse to change it.
	// Checked here before anything is applied, and again under the lock.
	if !records {
		if err := unrecordedExposureGuard(requested, lastMigration); err != nil {
			return false, err
		}
	}
	exposureKey := exposureJSON(exposure)

	// Phase 1 skip: schema, codegen version and exposure unchanged → skip entirely
	if !opts.Force && opts.DryRun == nil && schemaChecksum != "" {
		if shouldSkipMigration(lastMigration, schemaChecksum, exposureKey) {
			return true, nil
		}
	}

	// 4. Generate the SQL, the expected function names and their checksums
	// (pure computation, no DB).
	c, err := m.compile(types, exposure)
	if err != nil {
		return false, err
	}

	// Serialize the parsed model so the migration record is self-describing.
	modelJSON, err := schema.MarshalModel(types)
	if err != nil {
		return false, fmt.Errorf("marshaling model: %w", err)
	}
	write := migrationWrite{
		MelangeVersion:    opts.Version,
		SchemaChecksum:    schemaChecksum,
		FunctionNames:     c.names,
		FunctionChecksums: c.checksums,
		SchemaDSL:         opts.SchemaContent,
		SchemaFormat:      opts.SchemaFormat,
		ModelJSON:         modelJSON,
		Exposure:          exposureKey,
	}

	// 5. Handle dry-run mode
	if opts.DryRun != nil {
		drops, err := m.dryRunDrops(ctx, c.names, opts.Force)
		if err != nil {
			return false, err
		}
		if err := m.outputDryRun(opts.DryRun, write, c.check, c.list, drops); err != nil {
			return false, fmt.Errorf("writing dry-run SQL: %w", err)
		}
		return false, nil
	}

	// 6. Phase 2 skip: generated SQL is identical to what's already applied.
	// The schema, melange version or exposure changed (phase 1 didn't skip),
	// but the generated functions are byte-for-byte identical. Record the new
	// state but skip re-applying the functions. Plan predicts this same
	// decision. Unforced, the downgrade guard above already refused a
	// database that is ahead.
	if !opts.Force {
		switch planAction(lastMigration, schemaChecksum, exposureKey, c) {
		case PlanSkip:
			// Nothing changed at all (dev-build re-run that bypassed phase
			// 1): pure no-op, don't insert a migration record per run.
			return true, nil
		case PlanRecordOnly:
			skipped, err := m.recordMigrationOnly(ctx, write, opts.IfDeployedChecksum, requested)
			if !errors.Is(err, errDeployedFunctionsChanged) {
				return skipped, err
			}
			// Fall through: apply in full against what is deployed now.
		}
	}

	// 7. Apply everything atomically
	if txer, ok := m.db.(interface {
		BeginTx(ctx context.Context, opts *sql.TxOptions) (*sql.Tx, error)
	}); ok {
		tx, err := txer.BeginTx(ctx, nil)
		if err != nil {
			return false, fmt.Errorf("starting transaction: %w", err)
		}
		defer func() { _ = tx.Rollback() }()
		skip, err := m.apply(ctx, tx, true, opts, requested, write, c)
		if err != nil {
			_ = tx.Rollback()
			return false, m.withDependents(ctx, err)
		}
		if skip {
			return true, nil
		}
		return false, tx.Commit()
	}

	// Fall back to the caller's Execer (e.g. their own *sql.Tx, which holds the
	// lock until it commits).
	return m.apply(ctx, m.db, false, opts, requested, write, c)
}

// apply installs c and records write on db, under the migration lock. When
// ownTx, db is the migrator's own transaction: the caller commits, and any
// error rolls everything back.
//
// Without a transaction of its own there is no rollback, so every check that
// can refuse (the guards, the recheck, the dependents of orphaned functions)
// runs before any function is applied: a refusal then leaves nothing applied,
// matching the error. The exception is a dependent another session creates
// between that check and the drop (see dropFunctions). The lock only
// serializes when db is a transaction.
func (m *Migrator) apply(ctx context.Context, db Execer, ownTx bool, opts InternalMigrateOptions, requested *Exposure,
	write migrationWrite, c compiled,
) (skip bool, err error) {
	// Serialize with concurrent migrations (replicas migrating on startup)
	// before touching the tracking table, whose CREATE IF NOT EXISTS races.
	if err := m.lockMigrations(ctx, db); err != nil {
		return false, err
	}
	if err := m.applyMigrationsDDL(ctx, db); err != nil {
		return false, err
	}
	if skip, err := m.recheckUnderLock(ctx, db, opts, requested, write); err != nil || skip {
		return skip, err
	}

	// Functions the previous migration installed that this one no longer
	// generates are dropped; refuse when that would take user objects with
	// them. The drop itself refuses dependents created after this check.
	orphans, err := m.orphanedFunctions(ctx, db, c.names)
	if err != nil {
		return false, err
	}
	if err := m.refuseDependents(ctx, db, orphans, opts.Force); err != nil {
		return false, err
	}

	if err := m.applyGeneratedSQL(ctx, db, c.check); err != nil {
		return false, err
	}
	if err := m.applyGeneratedListSQL(ctx, db, c.list); err != nil {
		return false, err
	}
	if err := m.dropFunctions(ctx, db, ownTx, orphans, opts.Force); err != nil {
		return false, err
	}

	// Re-verify the drift guard inside the transaction before recording, so a
	// migration committed while this one was applying aborts it (rollback).
	if ownTx {
		if err := m.driftGuardInTx(ctx, db, opts.IfDeployedChecksum); err != nil {
			return false, err
		}
	}

	if write.SchemaChecksum != "" {
		if err := m.insertMigrationRecord(ctx, db, write); err != nil {
			return false, err
		}
	}
	return false, nil
}

// recheckUnderLock re-reads the latest record once the migration lock is held:
// a migration that held the lock before this one may have changed the deployed
// checksum or exposure, upgraded the database, or applied this exact state.
// It re-applies the drift guard (even under Force, like the up-front check),
// the downgrade guard and, for a run that records nothing, the exposure
// guard; starts the run over when the recorded exposure it kept has changed;
// and reports skip when the state is already applied.
func (m *Migrator) recheckUnderLock(ctx context.Context, db Execer, opts InternalMigrateOptions,
	requested *Exposure, write migrationWrite,
) (skip bool, err error) {
	rec, err := m.getLastMigration(ctx, db)
	if err != nil {
		return false, fmt.Errorf("checking last migration: %w", err)
	}
	if err := driftGuardError(opts.IfDeployedChecksum, rec); err != nil {
		return false, err
	}
	if err := inheritedExposureGuard(requested, rec, write.Exposure); err != nil {
		return false, err
	}
	// A run that records nothing passed the exposure guard against the record
	// it read up front; one committed while it waited for the lock may record
	// another exposure. (Dry-run never applies.)
	if opts.SchemaContent == "" {
		if err := unrecordedExposureGuard(requested, rec); err != nil {
			return false, err
		}
	}
	if opts.Force {
		return false, nil
	}
	if err := downgradeGuardError(rec); err != nil {
		return false, err
	}
	if write.SchemaChecksum == "" || !migrationRecordMatches(rec, write.SchemaChecksum, write.Exposure) {
		return false, nil
	}
	// Same phase 1 / phase 2 skip rules as the up-front checks.
	return shouldSkipMigration(rec, write.SchemaChecksum, write.Exposure) ||
		shouldSkipApply(rec, write.FunctionChecksums, write.FunctionNames), nil
}

// dryRunDrop is an orphaned function a dry-run script drops, with the objects
// that depended on it when the script was generated.
type dryRunDrop struct {
	Function   string
	Dependents []string
	Cascade    bool // forced: drop the dependents too
}

// dryRunDrops returns the functions migrate would drop as orphans, read from
// the database without changing it, each with its current dependents. Forced,
// the script drops those dependents with CASCADE; otherwise it refuses the
// drops when applied (see outputDryRun) as migrate would.
func (m *Migrator) dryRunDrops(ctx context.Context, expected []string, force bool) ([]dryRunDrop, error) {
	exists, err := m.migrationTableExists(ctx, m.db)
	if err != nil || !exists {
		return nil, err
	}
	orphans, err := m.orphanedFunctions(ctx, m.db, expected)
	if err != nil {
		return nil, err
	}
	drops := make([]dryRunDrop, len(orphans))
	index := make(map[string]int, len(orphans))
	for i, fn := range orphans {
		drops[i] = dryRunDrop{Function: fn, Cascade: force}
		index[fn] = i
	}
	deps, err := m.functionDependents(ctx, m.db, orphans)
	if err != nil {
		return nil, err
	}
	for _, d := range deps {
		i := index[d.Function]
		drops[i].Dependents = append(drops[i].Dependents, d.Object)
	}
	return drops, nil
}

// outputDryRun writes the migration SQL to dst and reports any write failure,
// so a truncated script (full disk, closed pipe) is never mistaken for a complete one.
//
// drops are the orphaned functions to drop after the new ones are created.
// Unless forced, they are dropped without CASCADE, and the script starts with
// a guard that raises when, at the time it is applied, other objects depend on
// any of them. The script is not one transaction, so the guard runs before it
// changes anything: applying it then refuses the drops the way migrate does,
// including for dependents created after the script was generated. A client
// that carries on after an error (psql without ON_ERROR_STOP) still applies
// the new functions, but the migration is recorded only once every orphan is
// gone, so the next migrate does not skip it.
func (m *Migrator) outputDryRun(dst io.Writer, write migrationWrite, generatedSQL GeneratedSQL, listSQL ListGeneratedSQL, drops []dryRunDrop) error {
	// bufio keeps the first write error and returns it from Flush, so the
	// individual writes below need no checks of their own.
	w := bufio.NewWriter(dst)
	melangeVersion := write.MelangeVersion
	schemaChecksum := write.SchemaChecksum
	expectedFunctions := write.FunctionNames

	// Header
	_, _ = fmt.Fprintf(w, "-- Melange Migration (dry-run)\n")
	if melangeVersion != "" {
		_, _ = fmt.Fprintf(w, "-- Melange version: %s\n", melangeVersion)
	}
	_, _ = fmt.Fprintf(w, "-- Schema checksum: %s\n", schemaChecksum)
	_, _ = fmt.Fprintf(w, "-- Codegen version: %s\n", CodegenVersion())
	if write.exposureOrDefault() != "{}" {
		_, _ = fmt.Fprintf(w, "-- Exposure: %s\n", write.Exposure)
	}
	_, _ = fmt.Fprintf(w, "\n")

	m.writeDependentsGuard(w, drops)

	// Database schema
	if m.databaseSchema != "" {
		_, _ = fmt.Fprintf(w, "-- ============================================================\n")
		_, _ = fmt.Fprintf(w, "-- Database schema: %s\n", m.databaseSchema)
		_, _ = fmt.Fprintf(w, "-- NOTE: You must create this schema before running the migration:\n")
		_, _ = fmt.Fprintf(w, "--   CREATE SCHEMA IF NOT EXISTS %s;\n", sqldsl.QuoteIdent(m.databaseSchema))
		_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	}

	// Migrations DDL (including column migrations for legacy tables)
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- DDL: Migration Tracking Table\n")
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	for _, stmt := range migrationsTableDDL(m.databaseSchema) {
		_, _ = fmt.Fprintf(w, "%s\n\n", stmt)
	}

	// Check functions
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- Check Functions (%d functions)\n", len(generatedSQL.Functions))
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	for _, fn := range generatedSQL.Functions {
		_, _ = fmt.Fprintf(w, "%s\n\n", fn)
	}

	// No-wildcard check functions
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- No-Wildcard Check Functions (%d functions)\n", len(generatedSQL.NoWildcardFunctions))
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	for _, fn := range generatedSQL.NoWildcardFunctions {
		_, _ = fmt.Fprintf(w, "%s\n\n", fn)
	}

	// Check dispatchers
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- Check Dispatchers\n")
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	if generatedSQL.Dispatcher != "" {
		_, _ = fmt.Fprintf(w, "%s\n\n", generatedSQL.Dispatcher)
	}
	if generatedSQL.DispatcherNoWildcard != "" {
		_, _ = fmt.Fprintf(w, "%s\n\n", generatedSQL.DispatcherNoWildcard)
	}
	if generatedSQL.BulkDispatcher != "" {
		_, _ = fmt.Fprintf(w, "%s\n\n", generatedSQL.BulkDispatcher)
	}

	// Explain functions + dispatcher (Stage 1: slice 1 — direct-grant only,
	// with cycle detection and a no-entry sentinel for unknown pairs).
	if len(generatedSQL.ExplainFunctions) > 0 || generatedSQL.ExplainDispatcher != "" {
		_, _ = fmt.Fprintf(w, "-- ============================================================\n")
		_, _ = fmt.Fprintf(w, "-- Explain Functions (%d functions)\n", len(generatedSQL.ExplainFunctions))
		_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
		for _, fn := range generatedSQL.ExplainFunctions {
			_, _ = fmt.Fprintf(w, "%s\n\n", fn)
		}
		if generatedSQL.ExplainDispatcher != "" {
			_, _ = fmt.Fprintf(w, "%s\n\n", generatedSQL.ExplainDispatcher)
		}
	}

	// Expand functions + dispatcher (Stage 2: slice 2.1 — direct + computed
	// only; TTU, intersection, exclusion, usersets, wildcards route to the
	// empty-leaf sentinel until later slices land).
	if len(generatedSQL.ExpandFunctions) > 0 || generatedSQL.ExpandDispatcher != "" {
		_, _ = fmt.Fprintf(w, "-- ============================================================\n")
		_, _ = fmt.Fprintf(w, "-- Expand Functions (%d functions)\n", len(generatedSQL.ExpandFunctions))
		_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
		for _, fn := range generatedSQL.ExpandFunctions {
			_, _ = fmt.Fprintf(w, "%s\n\n", fn)
		}
		if generatedSQL.ExpandDispatcher != "" {
			_, _ = fmt.Fprintf(w, "%s\n\n", generatedSQL.ExpandDispatcher)
		}
	}

	// List objects functions
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- List Objects Functions (%d functions)\n", len(listSQL.ListObjectsFunctions))
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	for _, fn := range listSQL.ListObjectsFunctions {
		_, _ = fmt.Fprintf(w, "%s\n\n", fn)
	}

	// List subjects functions
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- List Subjects Functions (%d functions)\n", len(listSQL.ListSubjectsFunctions))
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	for _, fn := range listSQL.ListSubjectsFunctions {
		_, _ = fmt.Fprintf(w, "%s\n\n", fn)
	}

	// List dispatchers
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- List Dispatchers\n")
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	if listSQL.ListObjectsDispatcher != "" {
		_, _ = fmt.Fprintf(w, "%s\n\n", listSQL.ListObjectsDispatcher)
	}
	if listSQL.ListSubjectsDispatcher != "" {
		_, _ = fmt.Fprintf(w, "%s\n\n", listSQL.ListSubjectsDispatcher)
	}

	// Accessible functions
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- Accessible Objects Functions\n")
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	if len(listSQL.AccessibleObjectsFunctions) > 0 {
		_, _ = fmt.Fprintf(w, "SET check_function_bodies = off;\n\n")
		for _, fn := range listSQL.AccessibleObjectsFunctions {
			_, _ = fmt.Fprintf(w, "%s\n\n", fn.SQL)
		}
		_, _ = fmt.Fprintf(w, "RESET check_function_bodies;\n\n")
	}

	// Orphaned functions, dropped after the new ones exist, as migrate does.
	if len(drops) > 0 {
		_, _ = fmt.Fprintf(w, "-- ============================================================\n")
		_, _ = fmt.Fprintf(w, "-- Drop Orphaned Functions (%d functions)\n", len(drops))
		_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
		for _, d := range drops {
			if len(d.Dependents) > 0 {
				if d.Cascade {
					_, _ = fmt.Fprintf(w, "-- WARNING: CASCADE also drops these dependents:\n")
				} else {
					_, _ = fmt.Fprintf(w, "-- WARNING: migrate refuses this drop without --force; dependents:\n")
				}
				for _, dep := range d.Dependents {
					_, _ = fmt.Fprintf(w, "--   %s\n", dep)
				}
			}
			_, _ = fmt.Fprintf(w, "%s;\n", m.dropFunctionSQL(d.Function, d.Cascade))
		}
		_, _ = fmt.Fprintf(w, "\n")
	}

	// Migration record
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- Migration Record\n")
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")

	// Sort function names for deterministic output
	sortedFunctions := make([]string, len(expectedFunctions))
	copy(sortedFunctions, expectedFunctions)
	sort.Strings(sortedFunctions)

	// Format as SQL array literal
	quotedFunctions := make([]string, len(sortedFunctions))
	for i, fn := range sortedFunctions {
		quotedFunctions[i] = sqldsl.Lit(fn).SQL()
	}

	// Emit every persisted column — including function_checksums and the
	// deployed-model columns — so a separately-applied dry-run script records a
	// migration identical to a normal migrate. Without function_checksums a later
	// real migrate could not take the phase-2 "skip-apply" fast path. sqldsl.Lit
	// escapes single quotes, so multi-line DSL and JSON are safe; the JSON text is
	// cast to the JSONB columns implicitly.
	checksumsJSON, err := json.Marshal(write.FunctionChecksums)
	if err != nil {
		// FunctionChecksums is a plain map[string]string; marshaling cannot fail.
		checksumsJSON = []byte("{}")
	}
	// With orphans to drop, the record is written only once they are gone: a
	// script applied past an error (psql without ON_ERROR_STOP continues
	// after the guard or a refused DROP) must not record a migration it did
	// not finish, or the next migrate would skip it.
	values, recordedIf := "VALUES (%s, %s, %s, ARRAY[%s], %s, %s, %s, %s, %s)", ""
	if len(drops) > 0 {
		orphans := make([]string, len(drops))
		for i, d := range drops {
			orphans[i] = sqldsl.Lit(d.Function).SQL()
		}
		values = "SELECT %s, %s, %s, ARRAY[%s], %s, %s, %s, %s, %s"
		recordedIf = fmt.Sprintf("\nWHERE NOT EXISTS (\n\tSELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace\n\tWHERE n.nspname = %s AND p.proname = ANY(ARRAY[%s]::TEXT[])\n)",
			m.postgresSchema(), strings.Join(orphans, ", "))
	}
	_, _ = fmt.Fprintf(w, "INSERT INTO %s (melange_version, schema_checksum, codegen_version, function_names, function_checksums, schema_dsl, schema_format, model_json, exposure)\n", m.prefixIdent("melange_migrations"))
	_, _ = fmt.Fprintf(w, values,
		sqldsl.Lit(melangeVersion).SQL(),
		sqldsl.Lit(schemaChecksum).SQL(),
		sqldsl.Lit(CodegenVersion()).SQL(),
		strings.Join(quotedFunctions, ", "),
		sqldsl.Lit(string(checksumsJSON)).SQL(),
		sqldsl.Lit(write.SchemaDSL).SQL(),
		sqldsl.Lit(write.SchemaFormat).SQL(),
		sqldsl.Lit(string(write.modelJSONOrEmpty())).SQL(),
		sqldsl.Lit(write.exposureOrDefault()).SQL(),
	)
	_, _ = fmt.Fprint(w, recordedIf+";\n")
	return w.Flush()
}

// writeDependentsGuard writes a DO block that raises when other objects
// depend on any orphan the script drops without CASCADE. It reads pg_depend
// when the script is applied, not when it was generated.
func (m *Migrator) writeDependentsGuard(w io.Writer, drops []dryRunDrop) {
	var names []string
	for _, d := range drops {
		if !d.Cascade {
			names = append(names, sqldsl.Lit(d.Function).SQL())
		}
	}
	if len(names) == 0 {
		return
	}
	_, _ = fmt.Fprintf(w, "-- ============================================================\n")
	_, _ = fmt.Fprintf(w, "-- Guard: refuse to drop functions other objects depend on\n")
	_, _ = fmt.Fprintf(w, "-- Apply the script so it stops at the first error, e.g.\n")
	_, _ = fmt.Fprintf(w, "--   psql -v ON_ERROR_STOP=1 --single-transaction -f <file>\n")
	_, _ = fmt.Fprintf(w, "-- ============================================================\n\n")
	_, _ = fmt.Fprintf(w, `DO $melange_guard$
DECLARE
	dependents TEXT;
BEGIN
	SELECT string_agg(d.obj || ' depends on ' || d.fn, '; ') INTO dependents
	FROM (%s) AS d(fn, obj);
	IF dependents IS NOT NULL THEN
		RAISE EXCEPTION 'migration would drop functions that other database objects depend on: %%', dependents
			USING HINT = 'Remove or change the dependents, or generate the script with --force to drop them with CASCADE.';
	END IF;
END
$melange_guard$;

`, m.functionDependentsQuery("ARRAY["+strings.Join(names, ", ")+"]::TEXT[]"))
}

func (m *Migrator) prefixIdent(identifier string) string {
	return sqldsl.PrefixIdent(identifier, m.databaseSchema)
}

func (m *Migrator) postgresSchema() string {
	return sqldsl.PostgresSchemaExpr(m.databaseSchema)
}
