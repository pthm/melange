const concurrencySchema = `model
  schema 1.1

type user

type group
  relations
    define member: [user, group#member]

type document
  relations
    define owner: [user]
    define editor: [user, group#member] or owner
    define viewer: [user] or editor
`

// writeSchema writes content to a temp schema file and returns its path.
func writeSchema(t *testing.T, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "schema.fga")
	require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
	return path
}

// newTuplesDB returns an empty database with a minimal melange_tuples table.
func newTuplesDB(t *testing.T) *sql.DB {
	t.Helper()
	db := testutil.EmptyDB(t)
	_, err := db.ExecContext(context.Background(), `CREATE TABLE melange_tuples (
		subject_type TEXT NOT NULL, subject_id TEXT NOT NULL, relation TEXT NOT NULL,
		object_type TEXT NOT NULL, object_id TEXT NOT NULL)`)
	require.NoError(t, err)
	return db
}

// stampVersion sets the codegen version for the test, restoring it afterwards.
// Unstamped "dev" builds bypass the downgrade guard and the phase 1 skip.
func stampVersion(t *testing.T, v string) {
	t.Helper()
	prev := version.Version
	version.Version = v
	t.Cleanup(func() { version.Version = prev })
}

// Replicas that run migrate on startup race against one database. The
// advisory lock serializes them: every run succeeds and only the first
// records a migration; the rest see it under the lock and skip.
func TestMigrate_ConcurrentReplicas(t *testing.T) {
	stampVersion(t, "v0.10.0")
	db := newTuplesDB(t)
	ctx := context.Background()
	schemaPath := writeSchema(t, concurrencySchema)

	const replicas = 8
	var wg sync.WaitGroup
	errs := make([]error, replicas)
	for i := range replicas {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_, errs[i] = migrator.MigrateWithOptions(ctx, db, schemaPath, migrator.MigrateOptions{Version: version.Version})
		}()
	}
	wg.Wait()
	require.NoError(t, errors.Join(errs...), "concurrent migrations must all succeed")

	var records int
	require.NoError(t, db.QueryRowContext(ctx, `SELECT count(*) FROM melange_migrations`).Scan(&records))
	require.Equal(t, 1, records, "only the first replica should record a migration")
}

// An older melange must not replace functions generated by a newer one: during
// a rolling deploy, old and new replicas would otherwise overwrite each other
// on every restart, and an old replica would undo codegen fixes.
func TestMigrate_RefusesOlderCodegen(t *testing.T) {
	db := newTuplesDB(t)
	ctx := context.Background()
	schemaPath := writeSchema(t, concurrencySchema)
	changedPath := writeSchema(t, concurrencySchema+"    define auditor: [user]\n")

	migrate := func(v, path string, force bool) error {
		stampVersion(t, v)
		_, err := migrator.MigrateWithOptions(ctx, db, path, migrator.MigrateOptions{Version: v, Force: force})
		return err
	}
	lastRecord := func() (codegen string, count int) {
		require.NoError(t, db.QueryRowContext(ctx,
			`SELECT codegen_version, (SELECT count(*) FROM melange_migrations) FROM melange_migrations ORDER BY id DESC LIMIT 1`,
		).Scan(&codegen, &count))
		return codegen, count
	}

	// A release binary (stamped without "v") upgrades a database last
	// migrated by a go-install build: versions compare as semver, not text.
	require.NoError(t, migrate("v0.10.0", schemaPath, false))
	require.NoError(t, migrate("0.11.0", schemaPath, false))
	codegen, records := lastRecord()
	require.Equal(t, "0.11.0", codegen)

	// The older replica restarting is refused, for the same schema and for a
	// changed one, and leaves the database untouched.
	for _, path := range []string{schemaPath, changedPath} {
		err := migrate("v0.10.0", path, false)
		var ahead *migrator.DatabaseAheadError
		require.ErrorAs(t, err, &ahead)
		require.Equal(t, "0.11.0", ahead.Deployed)
		gotCodegen, gotRecords := lastRecord()
		require.Equal(t, "0.11.0", gotCodegen)
		require.Equal(t, records, gotRecords, "a refused migration must not record anything")
	}
	var auditorFns int
	require.NoError(t, db.QueryRowContext(ctx,
		`SELECT count(*) FROM pg_proc WHERE proname LIKE '%auditor%'`).Scan(&auditorFns))
	require.Zero(t, auditorFns, "a refused migration must not apply functions")

	// Unstamped dev builds cannot be ordered and pass; Force downgrades.
	require.NoError(t, migrate("dev", schemaPath, false))
	require.NoError(t, migrate("0.12.0", schemaPath, false))
	require.NoError(t, migrate("v0.10.0", changedPath, true))
	codegen, _ = lastRecord()
	require.Equal(t, "v0.10.0", codegen)
}

// A migration that waits on the lock re-checks the guards once it holds it:
// a newer migration committed meanwhile must abort it, not be overwritten.
func TestMigrate_RechecksGuardsUnderLock(t *testing.T) {
	stampVersion(t, "v0.10.0")
	db := newTuplesDB(t)
	ctx := context.Background()
	schemaPath := writeSchema(t, concurrencySchema)
	changedPath := writeSchema(t, concurrencySchema+"    define auditor: [user]\n")
	_, err := migrator.MigrateWithOptions(ctx, db, schemaPath, migrator.MigrateOptions{Version: "v0.10.0"})
	require.NoError(t, err)
	var deployed string
	require.NoError(t, db.QueryRowContext(ctx,
		`SELECT schema_checksum FROM melange_migrations ORDER BY id DESC LIMIT 1`).Scan(&deployed))

	// runBehindLock holds the migration lock while migrate starts and queues
	// behind it, commits a record from a newer melange, then returns migrate's
	// result once it gets the lock.
	runBehindLock := func(opts migrator.MigrateOptions) error {
		tx, err := db.BeginTx(ctx, nil)
		require.NoError(t, err)
		defer func() { _ = tx.Rollback() }()
		_, err = tx.ExecContext(ctx, `SELECT pg_advisory_xact_lock(hashtext('melange'), hashtext(current_schema()))`)
		require.NoError(t, err)

		done := make(chan error, 1)
		go func() {
			_, err := migrator.MigrateWithOptions(ctx, db, changedPath, opts)
			done <- err
		}()
		// Wait until migrate is blocked on melange's lock in this database.
		// Polled on the test goroutine so an early return fails cleanly.
		deadline := time.Now().Add(10 * time.Second)
		for {
			select {
			case err := <-done:
				t.Fatalf("migrate returned before queuing behind the lock: %v", err)
			default:
			}
			var waiting bool
			require.NoError(t, db.QueryRowContext(ctx, `SELECT EXISTS (
				SELECT 1 FROM pg_locks
				WHERE locktype = 'advisory' AND NOT granted AND objsubid = 2
				AND database = (SELECT oid FROM pg_database WHERE datname = current_database())
				AND classid = hashtext('melange')::bigint::oid)`).Scan(&waiting))
			if waiting {
				break
			}
			require.True(t, time.Now().Before(deadline), "migrate never queued behind the lock")
			time.Sleep(10 * time.Millisecond)
		}

		_, err = tx.ExecContext(ctx, `INSERT INTO melange_migrations
			(melange_version, schema_checksum, codegen_version, function_names, function_checksums, schema_dsl, schema_format, model_json)
			SELECT melange_version, 'newer-checksum', 'v0.11.0', function_names, function_checksums, schema_dsl, schema_format, model_json
			FROM melange_migrations ORDER BY id DESC LIMIT 1`)
		require.NoError(t, err)
		require.NoError(t, tx.Commit())
		return <-done
	}

	var drift *migrator.DeployedModelChangedError
	require.ErrorAs(t, runBehindLock(migrator.MigrateOptions{Version: "v0.10.0", IfDeployedChecksum: &deployed}), &drift)

	// Drop the injected record so the next run passes the up-front checks.
	_, err = db.ExecContext(ctx, `DELETE FROM melange_migrations WHERE codegen_version = 'v0.11.0'`)
	require.NoError(t, err)

	var ahead *migrator.DatabaseAheadError
	require.ErrorAs(t, runBehindLock(migrator.MigrateOptions{Version: "v0.10.0"}), &ahead)

	var auditorFns int
	require.NoError(t, db.QueryRowContext(ctx,
		`SELECT count(*) FROM pg_proc WHERE proname LIKE '%auditor%'`).Scan(&auditorFns))
	require.Zero(t, auditorFns, "a migration refused under the lock must not apply functions")
}

// Callers may migrate inside their own transaction; concurrent ones serialize
// on the migration lock and only the first records the change. (Taking the
// lock before the up-front read also prevents a deadlock on the tracking
// table's DDL locks, but the window is too narrow to reproduce reliably here.)
func TestMigrate_ConcurrentCallerTransactions(t *testing.T) {
	stampVersion(t, "v0.10.0")
	db := newTuplesDB(t)
	ctx := context.Background()
	// Migrate once so the tracking table exists, then race on a change.
	_, err := migrator.MigrateWithOptions(ctx, db, writeSchema(t, concurrencySchema), migrator.MigrateOptions{Version: version.Version})
	require.NoError(t, err)
	schemaPath := writeSchema(t, concurrencySchema+"    define auditor: [user]\n")

	const callers = 6
	var wg sync.WaitGroup
	errs := make([]error, callers)
	for i := range callers {
		wg.Add(1)
		go func() {
			defer wg.Done()
			tx, err := db.BeginTx(ctx, nil)
			if err != nil {
				errs[i] = err
				return
			}
			defer func() { _ = tx.Rollback() }()
			if _, err := migrator.MigrateWithOptions(ctx, tx, schemaPath, migrator.MigrateOptions{Version: version.Version}); err != nil {
				errs[i] = err
				return
			}
			errs[i] = tx.Commit()
		}()
	}
	wg.Wait()
	require.NoError(t, errors.Join(errs...), "concurrent caller-owned transactions must all succeed")

	var records int
	require.NoError(t, db.QueryRowContext(ctx, `SELECT count(*) FROM melange_migrations`).Scan(&records))
	require.Equal(t, 2, records, "only the first caller should record the change")
}
