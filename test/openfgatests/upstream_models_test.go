package openfgatests_test

import (
	"flag"
	"os"
	"strings"
	"testing"

	"sigs.k8s.io/yaml"

	"github.com/pthm/melange/test/openfgatests"
)

var updateUpstreamModels = flag.Bool("update-upstream-models", false, "rewrite "+upstreamModelsPath+" from the embedded OpenFGA suite")

// upstreamModelsPath holds the models of the upstream OpenFGA suite for
// tests in the root module, which does not depend on github.com/openfga/openfga.
// internal/sqlgen's exposure soundness test reads it next to the local YAML.
const upstreamModelsPath = "../../internal/sqlgen/testdata/openfga_upstream_models.yaml"

const upstreamModelsHeader = `# Code generated by TestOpenFGA_UpstreamModelsVendored from the
# github.com/openfga/openfga assets/tests suite. DO NOT EDIT.
# Regenerate with: just update-upstream-models
`

// TestOpenFGA_UpstreamModelsVendored fails when upstreamModelsPath no longer
// matches the models of the embedded upstream suite, for example after an
// openfga version bump.
func TestOpenFGA_UpstreamModelsVendored(t *testing.T) {
	tests, err := openfgatests.LoadTests()
	if err != nil {
		t.Fatal(err)
	}
	type stage struct {
		Model string `json:"model,omitempty"`
	}
	type test struct {
		Name   string  `json:"name"`
		Stages []stage `json:"stages"`
	}
	var doc struct {
		Tests []test `json:"tests"`
	}
	for _, tc := range tests {
		if strings.HasPrefix(tc.Name, "melange/") {
			continue
		}
		vt := test{Name: tc.Name}
		for _, st := range tc.Stages {
			vt.Stages = append(vt.Stages, stage{Model: st.Model})
		}
		doc.Tests = append(doc.Tests, vt)
	}
	if len(doc.Tests) == 0 {
		t.Fatal("no upstream tests loaded")
	}
	out, err := yaml.Marshal(doc)
	if err != nil {
		t.Fatal(err)
	}
	want := upstreamModelsHeader + string(out)

	if *updateUpstreamModels {
		if err := os.WriteFile(upstreamModelsPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(upstreamModelsPath)
	if err != nil {
		t.Fatalf("%v (run just update-upstream-models)", err)
	}
	if string(got) != want {
		t.Errorf("%s is stale (run just update-upstream-models)", upstreamModelsPath)
	}
}
